/* ==========================================================
   Brain Snacks — Maze
   Drag the mouse to the cheese. Generated by recursive
   backtracking, so every maze has exactly one path and is
   always solvable. Spatial planning. Endless; grows each round.
   ========================================================== */

(function () {
  'use strict';

  var A = ART, S = A.S, G = A.G, ink = A.ink, txt = A.txt;

  var api, round, best, grid, cols, rows, cell, offX, offY;
  var hero, at2, goal, steps, playing, handle;

  var timers = [];
  function clearTimers() { for (var i = 0; i < timers.length; i++) { clearTimeout(timers[i]); } timers = []; }
  function later(fn, ms) { timers.push(setTimeout(fn, ms)); }

  var OPP = { n: 's', s: 'n', e: 'w', w: 'e' };

  function dims(r) {
    if (r < 2) { return [5, 6]; }
    if (r < 4) { return [6, 7]; }
    if (r < 6) { return [7, 9]; }
    if (r < 9) { return [8, 10]; }
    return [9, 11];
  }

  function gen(c, r) {
    var g = [], x, y;
    for (y = 0; y < r; y++) {
      g.push([]);
      for (x = 0; x < c; x++) { g[y].push({ n: 1, e: 1, s: 1, w: 1, v: 0 }); }
    }
    var stack = [[0, 0]];
    g[0][0].v = 1;
    while (stack.length) {
      var cur = stack[stack.length - 1], cx = cur[0], cy = cur[1], opts = [];
      if (cy > 0 && !g[cy - 1][cx].v) { opts.push('n'); }
      if (cy < r - 1 && !g[cy + 1][cx].v) { opts.push('s'); }
      if (cx > 0 && !g[cy][cx - 1].v) { opts.push('w'); }
      if (cx < c - 1 && !g[cy][cx + 1].v) { opts.push('e'); }
      if (!opts.length) { stack.pop(); continue; }
      var d = opts[Math.floor(Math.random() * opts.length)];
      var nx = cx + (d === 'e' ? 1 : (d === 'w' ? -1 : 0));
      var ny = cy + (d === 's' ? 1 : (d === 'n' ? -1 : 0));
      g[cy][cx][d] = 0;
      g[ny][nx][OPP[d]] = 0;
      g[ny][nx].v = 1;
      stack.push([nx, ny]);
    }
    return g;
  }

  function cx(x) { return offX + x * cell + cell / 2; }
  function cy(y) { return offY + y * cell + cell / 2; }

  function build() {
    var d = dims(round);
    cols = d[0]; rows = d[1];
    grid = gen(cols, rows);
    steps = 0;

    A.clear(api.arena);
    S('rect', { x: 0, y: 0, width: 360, height: 420, fill: A.vgrad(api.arena, '#3B2757', '#2B1B3F') }, api.arena);

    cell = Math.min(336 / cols, 396 / rows);
    offX = (360 - cell * cols) / 2;
    offY = (420 - cell * rows) / 2;

    S('rect', { x: offX - 5, y: offY - 5, width: cell * cols + 10, height: cell * rows + 10,
      rx: 12, fill: '#241534', opacity: '.35' }, api.arena);

    /* floor */
    var x, y;
    for (y = 0; y < rows; y++) {
      for (x = 0; x < cols; x++) {
        S('rect', { x: offX + x * cell, y: offY + y * cell, width: cell, height: cell,
          fill: (x + y) % 2 ? '#4A3372' : '#513C7C' }, api.arena);
      }
    }

    /* goal */
    goal = [cols - 1, rows - 1];
    var gg = G(api.arena, cx(goal[0]), cy(goal[1]));
    var cs = cell * .3;
    ink(S('path', { d: 'M' + (-cs) + ',' + (cs * .8) + ' L' + (-cs * .7) + ',' + (-cs) + ' L' + cs + ',' + (-cs * .5) + ' L' + (cs * .8) + ',' + (cs * .9) + ' Z',
      fill: '#FFD84A' }, gg), 3);
    S('circle', { cx: -cs * .2, cy: -cs * .1, r: cs * .22, fill: '#E0B44A' }, gg);
    S('circle', { cx: cs * .38, cy: cs * .38, r: cs * .16, fill: '#E0B44A' }, gg);

    /* walls */
    var w = S('g', {}, api.arena);
    function wall(x1, y1, x2, y2) {
      ink(S('line', { x1: x1, y1: y1, x2: x2, y2: y2 }, w), Math.max(4, cell * .17))
        .setAttribute('stroke', '#2B1B3F');
    }
    for (y = 0; y < rows; y++) {
      for (x = 0; x < cols; x++) {
        var px = offX + x * cell, py = offY + y * cell;
        if (grid[y][x].n) { wall(px, py, px + cell, py); }
        if (grid[y][x].w) { wall(px, py, px, py + cell); }
        if (x === cols - 1 && grid[y][x].e) { wall(px + cell, py, px + cell, py + cell); }
        if (y === rows - 1 && grid[y][x].s) { wall(px, py + cell, px + cell, py + cell); }
      }
    }

    at2 = [0, 0];
    hero = A.animal(api.arena, { kind: 'mouse', x: cx(0), y: cy(0) - cell * .18,
      size: cell * .2, fill: '#C9BFD6', shadow: false, bob: false });

    /* an invisible free-moving handle drives the stepping, so the mouse
       itself can stay snapped to the corridor and never clip a wall */
    handle = G(api.arena, cx(0), cy(0));
    S('rect', { x: -cell * .8, y: -cell * .8, width: cell * 1.6, height: cell * 1.6,
      fill: '#FFFFFF', opacity: '0', 'pointer-events': 'all' }, handle);
    BS.drag(handle, {
      onMove: function (hx, hy) {
        if (!playing) { return; }
        var tx = Math.floor((hx - offX) / cell), ty = Math.floor((hy - offY) / cell);
        if (tx < 0 || ty < 0 || tx >= cols || ty >= rows) { return; }
        step(tx, ty);
      },
      onDrop: function () { A.place(handle, cx(at2[0]), cy(at2[1])); }
    });

    api.score('Maze ' + (round + 1) + '  ' + cols + '\u00D7' + rows);
    api.bar(0);
  }

  function step(tx, ty) {
    var dx = tx - at2[0], dy = ty - at2[1];
    if (Math.abs(dx) + Math.abs(dy) !== 1) { return; }
    var d = dx === 1 ? 'e' : (dx === -1 ? 'w' : (dy === 1 ? 's' : 'n'));
    if (grid[at2[1]][at2[0]][d]) { return; }
    at2 = [tx, ty];
    steps++;
    BS.glide(hero, cx(tx), cy(ty) - cell * .18, 110);
    api.SFX.tap();
    var dist = Math.abs(tx - goal[0]) + Math.abs(ty - goal[1]);
    var far = cols + rows;
    api.bar(1 - dist / far);
    if (tx === goal[0] && ty === goal[1]) { won(); }
  }

  function won() {
    playing = false;
    round++;
    if (round > best) { best = round; api.save('bs.mazeBest', best); }
    api.SFX.win();
    api.confetti();
    api.toast('Cheese!', '#FFC93C');
    later(function () {
      if (round >= 10) {
        api.over('Maze master!', 'You solved every maze, right up to ' + cols + ' by ' + rows + '. Your best is ' + best + '.', 'Play again');
        return;
      }
      playing = true;
      build();
    }, 1200);
  }

  BS.registerMode('maze', {
    name: 'Maze', shelf: 'think', color: '#FF9E7A', shade: '#C46F52',
    keys: ['bs.mazeBest'], best: ['bs.mazeBest', 'maze', 'mazes'], blurb: 'Find the way out',
    icon: function (a) {
      ART.ink(ART.S('rect', { x: 20, y: 5, width: 44, height: 32, rx: 4, fill: '#4A3372' }, a), 2.6);
      ART.S('path', { d: 'M20,15 L44,15 M32,15 L32,27 M44,27 L64,27 M44,5 L44,17',
        stroke: '#241534', 'stroke-width': 3, 'stroke-linecap': 'round', fill: 'none' }, a);
      ART.S('circle', { cx: 26, cy: 10, r: 3.6, fill: '#C9BFD6' }, a);
      ART.S('circle', { cx: 58, cy: 33, r: 4, fill: '#FFD84A' }, a);
    },
    start: function (a) {
      api = a;
      clearTimers();
      api.title('Maze');
      api.showBar(true);
      api.foot('');
      best = api.load('bs.mazeBest', 0);
      round = 0; playing = true;
      build();
      api.toast('Drag to the cheese', '#FFC93C');
    },
    stop: function () { playing = false; clearTimers(); }
  });
})();
